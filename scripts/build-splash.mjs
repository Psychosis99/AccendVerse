// Inlines the anime.js UMD bundle into the splash page so it runs fully offline,
// and writes it as a TS string module consumed by the WebView / iframe splash.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = new URL('..', import.meta.url);
const template = readFileSync(new URL('src/splash/splash.html', root), 'utf8');
const animePath = require.resolve('animejs/package.json').replace(/package\.json$/, 'dist/bundles/anime.umd.min.js');
const anime = readFileSync(animePath, 'utf8').replace(/<\/script/gi, '<\\/script');

const html = template.replace('/*ANIME_JS*/', () => anime);
writeFileSync(
  new URL('src/splash/splashHtml.ts', root),
  `// Generated by scripts/build-splash.mjs from src/splash/splash.html. Do not edit.\nexport const SPLASH_HTML: string = ${JSON.stringify(html)};\n`,
);
console.log(`splashHtml.ts written (${(html.length / 1024).toFixed(0)} KB)`);
